-- ============================================================================
-- Tamil Business Tribe — FULL DATABASE MIGRATION
-- ============================================================================
-- Purpose: recreate every table, index, RLS policy, storage bucket, and the
-- minimal "functional default" seed data this codebase needs, inside a
-- DIFFERENT Supabase project (your existing/target project).
--
-- How to use:
--   1. Open your TARGET Supabase project -> SQL Editor -> New query.
--   2. Paste this entire file and click "Run".
--   3. It is idempotent (safe to re-run) — every CREATE uses IF NOT EXISTS
--      and every CREATE POLICY is preceded by a matching DROP POLICY IF EXISTS.
--   4. After running, update:
--        - admin-app/.env -> SUPABASE_URL / SUPABASE_KEY (service role key)
--          of the TARGET project, plus ANTHROPIC_API_KEY / CLAUDE_MODEL.
--        - lib/main.dart -> the hardcoded Supabase URL + anon key in main()
--          to the TARGET project's values.
--   5. Storage buckets are created at the bottom of this file (Section 15).
--      Supabase Storage bucket creation via SQL works, but it's worth opening
--      Dashboard -> Storage afterwards to visually confirm all 3 buckets
--      (community, ai-content, support-attachments) show up and are Public.
--
-- This file was generated by reverse-engineering every `supabase.from(...)`
-- / `.storage.from(...)` call across admin-app/ and lib/ against the existing
-- *_schema.sql files already in this repo, since a few tables (the E-book
-- module) were created by hand in Supabase Studio and were never scripted.
