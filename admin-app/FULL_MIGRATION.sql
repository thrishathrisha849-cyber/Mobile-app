-- ============================================================================
-- 15. STORAGE BUCKETS
-- ----------------------------------------------------------------------------
-- Every image/audio/PDF/video upload in this codebase funnels through exactly
-- 3 public buckets:
--   - "community"           generic uploads from the admin panel's single
--                            POST /api/upload route (server.js). Despite the
--                            name it holds carousel media, podcast covers +
--                            audio, e-book covers + PDFs, banners, and actual
--                            community-post media (folders like
--                            "podcast/covers", "ebooks/pdfs", etc.)
--   - "ai-content"          Content Buddy AI chat image attachments
--                            (imageUploadService.js), path pattern:
--                            {user_id}/{conversation_id}/{message_id}.jpg
--   - "support-attachments" ticket/feedback attachments uploaded directly
--                            from the Flutter app (support_service.dart)
-- ============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('community', 'community', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
VALUES ('ai-content', 'ai-content', true)
ON CONFLICT (id) DO NOTHING;

INSERT INTO storage.buckets (id, name, public)
VALUES ('support-attachments', 'support-attachments', true)
ON CONFLICT (id) DO NOTHING;

-- Public read for all 3 buckets (public URLs are used throughout the app).
DROP POLICY IF EXISTS "Public read - community" ON storage.objects;
CREATE POLICY "Public read - community" ON storage.objects
  FOR SELECT USING (bucket_id = 'community');

DROP POLICY IF EXISTS "Public read - ai-content" ON storage.objects;
CREATE POLICY "Public read - ai-content" ON storage.objects
  FOR SELECT USING (bucket_id = 'ai-content');

DROP POLICY IF EXISTS "Public read - support-attachments" ON storage.objects;
CREATE POLICY "Public read - support-attachments" ON storage.objects
  FOR SELECT USING (bucket_id = 'support-attachments');

-- Writes to "community" and "ai-content" only ever happen server-side from
-- admin-app, which uses the SUPABASE service-role key (bypasses RLS/storage
-- policies entirely) — so no INSERT/UPDATE/DELETE policy is required for
-- those two buckets to keep working exactly as today.
--
-- "support-attachments" is the one exception: the Flutter app uploads to it
-- directly using the anon key (see lib/support_service.dart), so it needs an
-- explicit public insert policy.
DROP POLICY IF EXISTS "Public insert - support-attachments" ON storage.objects;
CREATE POLICY "Public insert - support-attachments" ON storage.objects
  FOR INSERT WITH CHECK (bucket_id = 'support-attachments');

